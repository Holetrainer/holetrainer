def get_translator(lang):
    strings = TRANSLATIONS.get(lang, TRANSLATIONS["en"])

    def t(key, **kwargs):
        text = strings.get(key, TRANSLATIONS["en"].get(key, key))
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError):
                return text
        return text

    return t
